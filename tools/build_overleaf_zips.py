def words(paths):
    n = 0
    for p in paths:
        t = (P / p).read_text(encoding="utf-8")
        t = re.sub(r"%.*", "", t)
        t = re.sub(r"\\begin\{(tabular|table\*?|figure\*?)\}.*?\\end\{\1\}", " ", t, flags=re.S)
        t = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?(\{[^}]*\})?", " ", t)
        n += len(re.findall(r"[A-Za-z]{2,}", t))
    return n


def clickable_bib(text):
    """Turn every DOI into a clickable https://doi.org/... URL field (printed in blue by hyperref); entries that already have a URL keep it."""
    def fix(m):
        body = m.group(0)
        d = re.search(r"\n\s*doi\s*=\s*[{\"]([^}\"]+)[}\"],?", body)
        if not d:
            return body
        has_url = re.search(r"\burl\s*=", body) is not None
        body = body.replace(d.group(0), "" if has_url else "\n  url = {https://doi.org/" + d.group(1) + "},")
        return re.sub(r",\s*\n\}$", "\n}", body)
    return re.sub(r"@\w+\{[^,]+,.*?\n\}", fix, text, flags=re.S)


def build(name, main, sects, tabs, figs, kind, cls):
    out = DIST / name
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.write(P / main, "main.tex")
        for f in ["results_macros.tex"] + (["figs_all.tex"] if "journal" in main else ["figs_conf.tex"]):
            z.write(P / f, f)
        z.writestr("references.bib", clickable_bib((P / "references.bib").read_text(encoding="utf8")))
        for s in sects:
            z.write(P / "sections" / f"{s}.tex", f"sections/{s}.tex")
        for t in tabs:
            z.write(P / "tables" / f"{t}.tex", f"tables/{t}.tex")
        for f in figs:
            for ext in ("pdf", "png"):
                z.write(P / "figures" / f"{f}.{ext}", f"figures/{f}.{ext}")
        z.writestr("README_OVERLEAF.txt", README.format(kind=kind, cls=cls))
    return out


